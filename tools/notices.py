#!/usr/bin/env python3
"""Writes THIRD-PARTY-NOTICES.md from the licence files of what the rweb binary contains.

Run from the repository root after `zig build` has fetched the packages (zig-pkg/) and whenever a
pin changes (Ghostty in build.zig.zon, Zig itself, the vendored browser code); review the diff.
Usage: python3 tools/notices.py [ZIG_ROOT]   (default: found from `zig env`)
"""
import glob, json, os, subprocess, sys

def zig_root():
    if len(sys.argv) > 1:
        return sys.argv[1]
    out = subprocess.run(["zig", "env"], capture_output=True, text=True, check=True).stdout
    try:
        lib = json.loads(out)["lib_dir"]
    except ValueError:  # zig 0.17 prints ZON, not JSON
        lib = [l.split('"')[1] for l in out.splitlines() if l.strip().startswith(".lib_dir")][0]
    return os.path.dirname(os.path.dirname(os.path.abspath(lib)))

def one(pattern):
    hits = sorted(glob.glob(pattern))
    if len(hits) != 1:
        sys.exit(f"notices: expected one file for {pattern}, found {hits}")
    return hits[0]

def text(path):
    with open(path, encoding="utf-8") as f:
        return f.read().strip("\n")

ghostty = one("zig-pkg/ghostty-*/LICENSE").rsplit("/", 1)[0]
zr = zig_root()
parts = [
    ("Ghostty (libghostty-vt)", "MIT", "Linked into the binary. The page's `ghostty-vt.wasm` is a prebuilt WebAssembly build of Ghostty's terminal code taken as shipped in the `@wterm/ghostty` 0.6.0 package; that package does not record which Ghostty version it was built from.", f"{ghostty}/LICENSE"),
    ("simdutf", "Apache-2.0 or MIT; used under MIT", "Linked into the binary (vendored in Ghostty).", f"{ghostty}/pkg/simdutf/vendor/LICENSE-MIT"),
    ("Highway", "Apache-2.0 or BSD-3-Clause; used under BSD-3-Clause", "Linked into the binary.", one("zig-pkg/*/LICENSE-BSD3")),
    ("Wuffs", "MIT and Apache-2.0", "Linked into the binary.", one("zig-pkg/*/LICENSE-MIT").rsplit("/", 1)[0] + "/LICENSE"),
    ("uucode", "MIT", "Linked into the binary.", one("zig-pkg/uucode-*/LICENSE.md")),
    ("Unicode Character Database (through uucode)", "Unicode License V3", "Data compiled into the binary.", "tools/licenses/uucode-LICENSE_unicode"),
    ("UTF-8 decoder by Bjoern Hoehrmann (through uucode)", "MIT", "Linked into the binary.", "tools/licenses/uucode-LICENSE_Bjoern_Hoehrmann"),
    ("Zig standard library and runtime", "MIT", "Compiled into the binary.", f"{zr}/LICENSE"),
    ("musl libc", "MIT", "Linked into the Linux binary only.", f"{zr}/lib/zig/libc/musl/COPYRIGHT"),
    ("xterm.js 6.0.0 and its fit addon", "MIT", "Served by the binary to the browser.", "src/bridge/web/vendor/LICENSE-xterm.txt"),
    ("wterm 0.6.0", "Apache-2.0", "Served by the binary to the browser. `wterm.js` is a bundle of `@wterm/dom`, `@wterm/core` and `@wterm/ghostty` 0.6.0 and carries, base64-encoded inside it, a second WebAssembly module from those packages (55,081 bytes, SHA-256 `471458b178f3dae014ce4e87278b4bdc4f33220be2bd6ca36ad7de8b2f6de57f`).", "src/bridge/web/vendor/LICENSE-wterm.txt"),
]
out = ["# Third-party notices", "",
       "The rweb binary contains or serves the software below. Each entry gives its licence and the",
       "licence text as distributed with it. Also linked: LLVM's libc++, libc++abi, libunwind and",
       "compiler-rt (Apache-2.0 WITH LLVM-exception, which does not require attribution in binary form).",
       "Generated by `tools/notices.py`; do not edit by hand.", ""]
for name, lic, where, _ in parts:
    out.append(f"- **{name}**: {lic}. {where}")
for name, lic, where, path in parts:
    out += ["", f"## {name}", "", f"Licence: {lic}. {where}", "", "```text", text(path), "```"]
with open("THIRD-PARTY-NOTICES.md", "w", encoding="utf-8") as f:
    f.write("\n".join(out) + "\n")
print(f"THIRD-PARTY-NOTICES.md: {len(parts)} entries")
